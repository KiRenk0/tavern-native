private const val MAX_EXTERNAL_SOURCE_BYTES = 6 * 1024 * 1024
private val youtubeIdPattern = Regex("^[A-Za-z0-9_-]{11}$")
private val htmlScriptStyle = Regex("(?is)<(script|style|noscript|template|svg|nav|footer)\\b[^>]*>.*?</\\1\\s*>")
private val wikiNoiseBlock = Regex(
    "(?is)<(div|table|span|aside)\\b[^>]*class\\s*=\\s*[\"'][^\"']*\\b(mw-editsection|navbox|toc|reference|mw-empty-elt|noprint)\\b[^\"']*[\"'][^>]*>.*?</\\1\\s*>",
)
private val htmlBlockTag = Regex("(?i)</?(?:p|div|br|h[1-6]|li|tr|blockquote|section|article|hr)\\b[^>]*>")
private val htmlAnyTag = Regex("(?s)<[^>]+>")
private val citationBracket = Regex("\\[(?:\\d+|edit|编辑|citation needed)\\]", RegexOption.IGNORE_CASE)
private val multiBlankLines = Regex("\\n{3,}")
private val inlineSpaces = Regex("[ \\t\\x0B\\f\\r]+")
private val timedTextTag = Regex("(?is)<text\\b[^>]*>(.*?)</text>")
private val timedTextPTag = Regex("(?is)<p\\b[^>]*>(.*?)</p>")
private val timedTextSTag = Regex("(?is)<s\\b[^>]*>(.*?)</s>")
private val numericEntity = Regex("&#(?:x([0-9a-fA-F]+)|(\\d+));")

internal enum class ExternalSourceKind(val label: String) {
    AUTO("自动识别链接"),
    YOUTUBE("YouTube 字幕"),
    FANDOM("Fandom Wiki"),
    MEDIAWIKI("MediaWiki / 维基百科"),
}

internal data class WikiPageRef(
    val kind: ExternalSourceKind,
    val apiUrl: String,
    val title: String,
    val canonicalUrl: String,
    val strictMediaWiki: Boolean,
)

internal data class YouTubeCaptionTrack(
    val baseUrl: String,
    val languageCode: String,
    val name: String,
    val isAutoGenerated: Boolean,
)

internal data class YouTubeWatchMetadata(
    val title: String,
    val tracks: List<YouTubeCaptionTrack>,
)

private val knownMediaWikiDomains = setOf(
    "wikipedia.org", "wiktionary.org", "wikibooks.org", "wikisource.org",
    "wikiquote.org", "wikiversity.org", "wikivoyage.org", "mediawiki.org",
    "wikimedia.org", "moegirl.org.cn", "wiki.biligame.com", "huijiwiki.com",
)

internal fun extractYouTubeVideoId(input: String): String? {
    val trimmed = input.trim()
    if (trimmed.isEmpty()) return null
    if (trimmed.startsWith("youtube:", ignoreCase = true)) {
        val candidate = trimmed.substringAfter(':').substringBefore('?').trim()
        return candidate.takeIf(youtubeIdPattern::matches)
    }
    if (youtubeIdPattern.matches(trimmed)) return trimmed
    val uri = runCatching { URI(trimmed) }.getOrNull() ?: return null
    val host = uri.host?.lowercase(Locale.ROOT)?.removePrefix("www.")?.removePrefix("m.") ?: return null
    if (host == "youtu.be") {
        val seg = uri.path.orEmpty().trim('/').substringBefore('/')
        return seg.takeIf(youtubeIdPattern::matches)
    }
    if (host == "youtube.com" || host == "youtube-nocookie.com" || host == "music.youtube.com") {
        val path = uri.path.orEmpty()
        val query = parseQueryParams(uri.rawQuery)
        query["v"]?.takeIf(youtubeIdPattern::matches)?.let { return it }
        val segments = path.trim('/').split('/')
        if (segments.size >= 2 && segments[0] in setOf("shorts", "embed", "live", "v")) {
            return segments[1].takeIf(youtubeIdPattern::matches)
        }
    }
    return null
}

internal fun extractYouTubePreferredLang(input: String): String {
    val uri = runCatching { URI(input.trim()) }.getOrNull() ?: return ""
    val query = parseQueryParams(uri.rawQuery)
    return query["lang"]?.trim().orEmpty().ifBlank { query["hl"]?.trim().orEmpty() }
}

internal fun buildYouTubeImportUrl(input: String, lang: String = ""): String {
    val id = extractYouTubeVideoId(input)
        ?: throw IllegalArgumentException("请输入有效的 YouTube 链接或 11 位视频 ID")
    val cleanLang = lang.trim()
    return if (cleanLang.isBlank()) "https://www.youtube.com/watch?v=$id"
    else "https://www.youtube.com/watch?v=$id&lang=${URLEncoder.encode(cleanLang, "UTF-8")}"
}

internal fun parseFandomUrl(url: String): WikiPageRef? {
    val uri = runCatching { URI(url.trim()) }.getOrNull() ?: return null
    if (uri.scheme !in setOf("http", "https") || uri.rawUserInfo != null) return null
    val host = uri.host?.lowercase(Locale.ROOT) ?: return null
    if (!host.endsWith(".fandom.com") && !host.endsWith(".wikia.org") && !host.endsWith(".wikia.com")) return null
    val rawPath = uri.rawPath.orEmpty()
    val wikiIdx = rawPath.indexOf("/wiki/")
    val prefix = if (wikiIdx > 0) rawPath.substring(0, wikiIdx) else ""
    val title = when {
        wikiIdx >= 0 -> decodeWikiTitle(rawPath.substring(wikiIdx + "/wiki/".length))
        else -> parseQueryParams(uri.rawQuery)["title"]?.let(::decodeWikiTitle).orEmpty()
    }
    if (title.isBlank()) return null
    val port = if (uri.port > 0) ":${uri.port}" else ""
    val apiUrl = "${uri.scheme}://$host$port$prefix/api.php"
    return WikiPageRef(ExternalSourceKind.FANDOM, apiUrl, title, url.trim(), strictMediaWiki = true)
}

internal fun buildFandomImportUrl(wikiOrUrl: String, pageTitle: String): String {
    val cleanWiki = wikiOrUrl.trim()
    val cleanPage = pageTitle.trim()
    if (parseFandomUrl(cleanWiki) != null) return cleanWiki
    require(cleanWiki.isNotBlank() && cleanPage.isNotBlank()) { "请填写 Fandom 站点名与词条名称" }
    val subdomain = cleanWiki.removePrefix("https://").removePrefix("http://")
        .substringBefore('/').removeSuffix(".fandom.com").trim()
    require(subdomain.matches(Regex("^[a-zA-Z0-9-]+$"))) { "Fandom 子域名格式无效" }
    val encodedPage = URLEncoder.encode(cleanPage.replace(' ', '_'), "UTF-8").replace("+", "%20")
    return "https://$subdomain.fandom.com/wiki/$encodedPage"
}

internal fun parseMediaWikiUrl(url: String): WikiPageRef? {
    val uri = runCatching { URI(url.trim()) }.getOrNull() ?: return null
    if (uri.scheme !in setOf("http", "https") || uri.rawUserInfo != null) return null
    val host = uri.host?.lowercase(Locale.ROOT) ?: return null
    if (host.endsWith(".fandom.com") || host.endsWith(".wikia.org") || host.endsWith(".wikia.com")) return null
    val isKnown = knownMediaWikiDomains.any { host == it || host.endsWith(".$it") }
    val rawPath = uri.rawPath.orEmpty()
    val query = parseQueryParams(uri.rawQuery)
    val port = if (uri.port > 0) ":${uri.port}" else ""
    val origin = "${uri.scheme}://$host$port"

    val wikiIdx = rawPath.indexOf("/wiki/")
    if (wikiIdx >= 0) {
        val title = decodeWikiTitle(rawPath.substring(wikiIdx + "/wiki/".length))
        if (title.isBlank()) return null
        val prefix = rawPath.substring(0, wikiIdx)
        val apiPath = if (isKnown && host.endsWith("wikipedia.org") || isKnown && host.endsWith("wikimedia.org") ||
            isKnown && host.endsWith("wiktionary.org") || isKnown && host.endsWith("wikibooks.org") ||
            isKnown && host.endsWith("wikisource.org") || isKnown && host.endsWith("wikiquote.org") ||
            isKnown && host.endsWith("wikiversity.org") || isKnown && host.endsWith("wikivoyage.org") ||
            isKnown && host.endsWith("mediawiki.org")
        ) "$prefix/w/api.php" else "$prefix/api.php"
        val normalizedHost = host.replace(".m.wikipedia.org", ".wikipedia.org")
        return WikiPageRef(
            kind = ExternalSourceKind.MEDIAWIKI,
            apiUrl = "${uri.scheme}://$normalizedHost$port$apiPath",
            title = title,
            canonicalUrl = url.trim(),
            strictMediaWiki = isKnown,
        )
    }
    val queryTitle = query["title"]?.let(::decodeWikiTitle).orEmpty()
    if (queryTitle.isNotBlank() && (rawPath.endsWith("/index.php") || rawPath.endsWith("/w/index.php"))) {
        val apiPath = rawPath.removeSuffix("index.php") + "api.php"
        return WikiPageRef(
            kind = ExternalSourceKind.MEDIAWIKI,
            apiUrl = "$origin$apiPath",
            title = queryTitle,
            canonicalUrl = url.trim(),
            strictMediaWiki = isKnown || rawPath.endsWith("/w/index.php"),
        )
    }
    return null
}

internal fun buildMediaWikiImportUrl(siteUrl: String, pageTitle: String): String {
    val cleanSite = siteUrl.trim()
    val cleanPage = pageTitle.trim()
    if (parseMediaWikiUrl(cleanSite) != null && cleanPage.isBlank()) return cleanSite
    require(cleanSite.isNotBlank() && cleanPage.isNotBlank()) { "请填写 MediaWiki 站点地址与词条名称" }
    val uri = checkedAddress(cleanSite)
    val base = uri.toString().trimEnd('/').removeSuffix("/api.php").removeSuffix("/w/api.php")
        .removeSuffix("/index.php").removeSuffix("/w/index.php").removeSuffix("/wiki")
    val encoded = URLEncoder.encode(cleanPage.replace(' ', '_'), "UTF-8").replace("+", "%20")
    return "$base/wiki/$encoded"
}

internal fun parseYouTubeWatchPage(html: String): YouTubeWatchMetadata {
    val jsonText = extractAssignedJsonObject(html, "ytInitialPlayerResponse")
        ?: error("未能从 YouTube 页面提取播放器元数据")
    val root = JSONObject(jsonText)
    val title = root.optJSONObject("videoDetails")?.string("title").orEmpty().ifBlank { "YouTube 视频字幕" }
    val tracksArray = root.optJSONObject("captions")
        ?.optJSONObject("playerCaptionsTracklistRenderer")
        ?.optJSONArray("captionTracks")
        ?: JSONArray()
    val tracks = mutableListOf<YouTubeCaptionTrack>()
    for (i in 0 until tracksArray.length()) {
        val item = tracksArray.optJSONObject(i) ?: continue
        val baseUrl = item.string("baseUrl").replace("\\u0026", "&").trim()
        if (baseUrl.isEmpty()) continue
        val lang = item.string("languageCode").trim()
        val nameObj = item.optJSONObject("name")
        val name = nameObj?.string("simpleText").orEmpty()
            .ifBlank { nameObj?.optJSONArray("runs")?.optJSONObject(0)?.string("text").orEmpty() }
            .ifBlank { lang }
        val isAsr = item.string("kind").equals("asr", ignoreCase = true)
        tracks += YouTubeCaptionTrack(baseUrl, lang, name, isAsr)
    }
    return YouTubeWatchMetadata(title, tracks)
}

internal fun selectCaptionTrack(tracks: List<YouTubeCaptionTrack>, preferredLang: String = ""): YouTubeCaptionTrack? {
    if (tracks.isEmpty()) return null
    val pref = preferredLang.trim().lowercase(Locale.ROOT)
    val prefBase = pref.substringBefore('-')
    fun score(track: YouTubeCaptionTrack): Int {
        val lang = track.languageCode.lowercase(Locale.ROOT)
        val langBase = lang.substringBefore('-')
        var s = if (track.isAutoGenerated) 0 else 10
        if (pref.isNotBlank()) {
            if (lang == pref) s += 100
            else if (langBase == prefBase) s += 60
        } else {
            if (langBase == "zh") s += 30
            else if (langBase == "en") s += 25
        }
        return s
    }
    return tracks.maxByOrNull(::score)
}

internal fun parseYouTubeTimedTextXml(xml: String): String {
    val lines = mutableListOf<String>()
    val textMatches = timedTextTag.findAll(xml).toList()
    if (textMatches.isNotEmpty()) {
        for (m in textMatches) {
            val cleaned = unescapeHtmlEntities(unescapeHtmlEntities(m.groupValues[1]))
                .replace('\n', ' ')
                .replace(inlineSpaces, " ")
                .trim()
            if (cleaned.isNotEmpty()) lines += cleaned
        }
    } else {
        for (p in timedTextPTag.findAll(xml)) {
            val inner = p.groupValues[1]
            val segs = timedTextSTag.findAll(inner).map { it.groupValues[1] }.toList()
            val combined = if (segs.isNotEmpty()) segs.joinToString("") else inner
            val cleaned = unescapeHtmlEntities(unescapeHtmlEntities(htmlAnyTag.replace(combined, "")))
                .replace('\n', ' ')
                .replace(inlineSpaces, " ")
                .trim()
            if (cleaned.isNotEmpty()) lines += cleaned
        }
    }
    return lines.joinToString("\n")
}

internal fun parseYouTubeTimedTextJson3(raw: String): String {
    val root = JSONObject(raw)
    val events = root.optJSONArray("events") ?: return ""
    val lines = mutableListOf<String>()
    for (i in 0 until events.length()) {
        val event = events.optJSONObject(i) ?: continue
        val segs = event.optJSONArray("segs") ?: continue
        val text = buildString {
            for (j in 0 until segs.length()) {
                append(segs.optJSONObject(j)?.string("utf8").orEmpty())
            }
        }.replace('\n', ' ').replace(inlineSpaces, " ").trim()
        if (text.isNotEmpty()) lines += text
    }
    return lines.joinToString("\n")
}

internal suspend fun importYouTubeTranscript(
    urlOrId: String,
    preferredLang: String = "",
    fetch: suspend (String) -> String = ::fetchExternalText,
): ImportedDocument {
    val videoId = extractYouTubeVideoId(urlOrId)
        ?: throw IllegalArgumentException("无法识别 YouTube 视频 ID")
    val lang = preferredLang.trim().ifBlank { extractYouTubePreferredLang(urlOrId) }
    val watchUrl = "https://www.youtube.com/watch?v=$videoId"
    val watchHtml = fetch(watchUrl)
    val metadata = parseYouTubeWatchPage(watchHtml)
    val track = selectCaptionTrack(metadata.tracks, lang)
        ?: error("该 YouTube 视频没有可用的字幕轨道")
    val captionUri = runCatching { URI(track.baseUrl) }.getOrNull()
    val captionHost = captionUri?.host?.lowercase(Locale.ROOT).orEmpty()
    require(
        captionUri != null && captionUri.scheme == "https" && captionUri.rawUserInfo == null &&
            (captionHost == "www.youtube.com" || captionHost.endsWith(".youtube.com") || captionHost == "youtube.com"),
    ) { "YouTube 字幕轨道地址无效" }
    val payload = fetch(track.baseUrl)
    val trimmed = payload.trimStart()
    val transcript = if (trimmed.startsWith("{")) parseYouTubeTimedTextJson3(trimmed) else parseYouTubeTimedTextXml(trimmed)
    require(transcript.isNotBlank()) { "YouTube 字幕内容为空" }
    val docTitle = "YouTube · ${metadata.title}".take(180)
    val body = buildString {
        appendLine("Title: ${metadata.title}")
        appendLine("Source: $watchUrl")
        if (track.languageCode.isNotBlank()) appendLine("Language: ${track.languageCode}")
        appendLine()
        append(transcript)
    }
    return ImportedDocument(docTitle, validatedDocumentText(body))
}

internal fun parseMediaWikiExtractJson(raw: String): ImportedDocument? {
    val root = JSONObject(raw)
    val pages = root.optJSONObject("query")?.opt("pages") ?: return null
    val page = when (pages) {
        is JSONArray -> pages.optJSONObject(0)
        is JSONObject -> pages.keys().asSequence().firstOrNull()?.let { pages.optJSONObject(it) }
        else -> null
    } ?: return null
    if (page.optBoolean("missing", false)) return null
    val title = page.string("title").trim()
    val extract = page.string("extract").trim()
    if (extract.isBlank()) return null
    return ImportedDocument(title.ifBlank { "Wiki 词条" }.take(180), validatedDocumentText(extract))
}

internal fun parseMediaWikiParseJson(raw: String): ImportedDocument? {
    val root = JSONObject(raw)
    if (root.has("error")) return null
    val parse = root.optJSONObject("parse") ?: return null
    val rawTitle = parse.string("displaytitle").ifBlank { parse.string("title") }
    val title = stripWikiHtml(rawTitle).replace('\n', ' ').trim().ifBlank { "Wiki 词条" }
    val htmlField = parse.opt("text")
    val html = when (htmlField) {
        is String -> htmlField
        is JSONObject -> htmlField.string("*")
        else -> ""
    }
    if (html.isBlank()) return null
    val text = stripWikiHtml(html)
    if (text.isBlank()) return null
    return ImportedDocument(title.take(180), validatedDocumentText(text))
}

internal suspend fun importFandomArticle(
    ref: WikiPageRef,
    fetch: suspend (String) -> String = ::fetchExternalText,
): ImportedDocument {
    val encoded = URLEncoder.encode(ref.title, "UTF-8")
    val parseUrl = "${ref.apiUrl}?action=parse&page=$encoded&prop=text%7Cdisplaytitle&redirects=1&format=json&formatversion=2"
    val parseResult = runCatching { parseMediaWikiParseJson(fetch(parseUrl)) }.getOrNull()
    if (parseResult != null) return parseResult
    val extractUrl = "${ref.apiUrl}?action=query&prop=extracts&explaintext=1&redirects=1&titles=$encoded&format=json&formatversion=2"
    return parseMediaWikiExtractJson(fetch(extractUrl))
        ?: error("未能从 Fandom Wiki 提取词条：${ref.title}")
}

internal suspend fun importMediaWikiPage(
    ref: WikiPageRef,
    fetch: suspend (String) -> String = ::fetchExternalText,
): ImportedDocument {
    val encoded = URLEncoder.encode(ref.title, "UTF-8")
    val extractUrl = "${ref.apiUrl}?action=query&prop=extracts&explaintext=1&exsectionformat=plain&redirects=1&titles=$encoded&format=json&formatversion=2"
    val extractResult = runCatching { parseMediaWikiExtractJson(fetch(extractUrl)) }.getOrNull()
    if (extractResult != null) return extractResult
    val parseUrl = "${ref.apiUrl}?action=parse&page=$encoded&prop=text%7Cdisplaytitle&redirects=1&format=json&formatversion=2"
    return parseMediaWikiParseJson(fetch(parseUrl))
        ?: error("未能从 MediaWiki 提取词条：${ref.title}")
}

internal suspend fun importExternalSourceIfMatched(
    value: String,
    fetch: suspend (String) -> String = ::fetchExternalText,
): ImportedDocument? {
    val trimmed = value.trim()
    if (extractYouTubeVideoId(trimmed) != null) {
        return importYouTubeTranscript(trimmed, fetch = fetch)
    }
    parseFandomUrl(trimmed)?.let { fandom ->
        return importFandomArticle(fandom, fetch = fetch)
    }
    parseMediaWikiUrl(trimmed)?.let { wiki ->
        return if (wiki.strictMediaWiki) {
            importMediaWikiPage(wiki, fetch = fetch)
        } else {
            runCatching { importMediaWikiPage(wiki, fetch = fetch) }.getOrNull()
        }
    }
    return null
}

internal fun stripWikiHtml(html: String): String {
    var cleaned = htmlScriptStyle.replace(html, " ")
    cleaned = wikiNoiseBlock.replace(cleaned, " ")
    cleaned = htmlBlockTag.replace(cleaned, "\n")
    cleaned = htmlAnyTag.replace(cleaned, "")
    cleaned = unescapeHtmlEntities(cleaned)
    cleaned = citationBracket.replace(cleaned, "")
    return cleaned.lineSequence()
        .map { inlineSpaces.replace(it, " ").trim() }
        .joinToString("\n")
        .let { multiBlankLines.replace(it, "\n\n").trim() }
}

internal fun unescapeHtmlEntities(text: String): String {
    if ('&' !in text) return text
    val named = text
        .replace("&nbsp;", " ")
        .replace("&quot;", "\"")
        .replace("&apos;", "'")
        .replace("&#39;", "'")
        .replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&mdash;", "—")
        .replace("&ndash;", "–")
        .replace("&hellip;", "…")
    val numeric = numericEntity.replace(named) { m ->
        val hex = m.groupValues[1]
        val dec = m.groupValues[2]
        val code = if (hex.isNotEmpty()) hex.toIntOrNull(16) else dec.toIntOrNull(10)
        if (code != null && Character.isValidCodePoint(code)) String(Character.toChars(code)) else m.value
    }
    return numeric.replace("&amp;", "&")
}

private suspend fun fetchExternalText(url: String): String = request(
    url = url,
    headers = mapOf(
        "Accept" to "application/json, text/html, application/xml, text/xml, text/plain",
        "User-Agent" to "TavernNative/1.0 (DataBank Importer)",
    ),
    readTimeout = 30_000,
    followRedirects = true,
) { input, type ->
    decodeDocumentText(input.readLimited(MAX_EXTERNAL_SOURCE_BYTES), type, inspectMarkup = true)
}

private fun decodeWikiTitle(raw: String): String {
    val clean = raw.substringBefore('#').substringBefore('?').trim('/')
    return runCatching { URLDecoder.decode(clean, "UTF-8") }.getOrDefault(clean).replace('_', ' ').trim()
}

private fun parseQueryParams(rawQuery: String?): Map<String, String> {
    if (rawQuery.isNullOrBlank()) return emptyMap()
    return rawQuery.split('&').mapNotNull { part ->
        val eq = part.indexOf('=')
        if (eq <= 0) return@mapNotNull null
        val key = runCatching { URLDecoder.decode(part.substring(0, eq), "UTF-8") }.getOrDefault(part.substring(0, eq))
        val value = runCatching { URLDecoder.decode(part.substring(eq + 1), "UTF-8") }.getOrDefault(part.substring(eq + 1))
        key to value
    }.toMap()
}

private fun extractAssignedJsonObject(source: String, marker: String): String? {
    val idx = source.indexOf(marker)
    if (idx < 0) return null
    val start = source.indexOf('{', idx + marker.length)
    if (start < 0) return null
    var depth = 0
    var inString = false
    var escaped = false
    for (i in start until source.length) {
        val c = source[i]
        if (inString) {
            if (escaped) escaped = false
            else if (c == '\\') escaped = true
            else if (c == '"') inString = false
        } else {
            when (c) {
                '"' -> inString = true
                '{' -> depth++
                '}' -> {
                    depth--
                    if (depth == 0) return source.substring(start, i + 1)
                }
            }
        }
    }
    return null
}
